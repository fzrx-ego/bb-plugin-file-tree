#!/usr/bin/env node
/**
 * Regenerates lib/seti-icons.generated.ts from VS Code's built-in Seti icon
 * theme (extensions/theme-seti, MIT) at a pinned commit. The theme maps some
 * files directly and the rest through VS Code language ids, so the language
 * contributions of VS Code's built-in extensions are read too: that is how
 * `.jl` reaches Julia's icon. Run: npm run generate:icons
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const VSCODE_COMMIT = "9f2b9e70d7137de823db221398c14bd9d6adc10d";
const RAW = `https://raw.githubusercontent.com/microsoft/vscode/${VSCODE_COMMIT}`;
const OUT = fileURLToPath(new URL("../lib/seti-icons.generated.ts", import.meta.url));

async function fetchOk(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response;
}

async function languageContributions() {
  const entries = await (await fetchOk(
    `https://api.github.com/repos/microsoft/vscode/contents/extensions?ref=${VSCODE_COMMIT}`,
  )).json();
  const manifests = await Promise.all(
    entries
      .filter((entry) => entry.type === "dir")
      .map(async (entry) => {
        const response = await fetch(`${RAW}/extensions/${entry.name}/package.json`);
        return response.ok ? response.json() : null;
      }),
  );
  return manifests.flatMap((manifest) => manifest?.contributes?.languages ?? []);
}

function sorted(record) {
  return Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)));
}

const theme = await (await fetchOk(`${RAW}/extensions/theme-seti/icons/vs-seti-icon-theme.json`)).json();
const font = Buffer.from(await (await fetchOk(`${RAW}/extensions/theme-seti/icons/seti.woff`)).arrayBuffer());

const fileNames = {};
for (const [name, id] of Object.entries(theme.fileNames)) fileNames[name.toLowerCase()] = id;
const fileExtensions = {};
for (const [ext, id] of Object.entries(theme.fileExtensions)) fileExtensions[ext.toLowerCase()] = id;

const languageFileNames = {};
const languageFileExtensions = {};
for (const language of await languageContributions()) {
  const id = theme.languageIds[language.id];
  if (id === undefined) continue;
  for (const name of language.filenames ?? []) languageFileNames[name.toLowerCase()] ??= id;
  for (const ext of language.extensions ?? []) {
    languageFileExtensions[ext.replace(/^\./u, "").toLowerCase()] ??= id;
  }
}

const ids = Object.keys(theme.iconDefinitions).filter((id) => !id.endsWith("_light"));
const icons = {};
for (const id of ids) {
  const dark = theme.iconDefinitions[id];
  const light = theme.iconDefinitions[`${id}_light`] ?? dark;
  const codePoint = Number.parseInt(dark.fontCharacter.replace(/^\\/u, ""), 16);
  icons[id] = [String.fromCodePoint(codePoint), dark.fontColor ?? "currentColor", light.fontColor ?? "currentColor"];
}

const json = (value) => JSON.stringify(value, null, 2);
writeFileSync(OUT, `/**
 * Generated by scripts/generate-seti-icons.mjs — do not edit.
 * From VS Code's Seti icon theme (microsoft/vscode@${VSCODE_COMMIT.slice(0, 12)},
 * extensions/theme-seti), itself built from jesseweed/seti-ui.
 * Copyright (c) Microsoft Corporation; Copyright (c) 2014 Jesse Weed. MIT License.
 */

/** Icon id → [glyph, dark-theme color, light-theme color]. */
export const SETI_ICONS: Record<string, readonly [string, string, string]> = ${json(sorted(icons))};

export const SETI_DEFAULT_ICON = ${json(theme.file)};

export const SETI_FILE_NAMES: Record<string, string> = ${json(sorted(fileNames))};

export const SETI_FILE_EXTENSIONS: Record<string, string> = ${json(sorted(fileExtensions))};

export const SETI_LANGUAGE_FILE_NAMES: Record<string, string> = ${json(sorted(languageFileNames))};

export const SETI_LANGUAGE_FILE_EXTENSIONS: Record<string, string> = ${json(sorted(languageFileExtensions))};

export const SETI_FONT_WOFF_BASE64 =
  "${font.toString("base64")}";
`);
console.log(`Wrote ${OUT}: ${ids.length} icons, ${Object.keys(fileExtensions).length + Object.keys(languageFileExtensions).length} extensions, ${Object.keys(fileNames).length + Object.keys(languageFileNames).length} file names.`);
