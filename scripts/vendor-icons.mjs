import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import { iconImports, iconModule, upstream } from './icon-imports.mjs';

const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/vendor-icons.mjs /path/to/core-free-icons [--check]');
const packageRoot = resolve(source);
const manifest = JSON.parse(await readFile(resolve(packageRoot, 'package.json'), 'utf8'));
if (manifest.name !== upstream || manifest.version !== '4.3.0') {
  throw new Error('Expected @hugeicons/core-free-icons@4.3.0');
}
const names = [...new Set((await iconImports()).flatMap(item => item.names))].sort();
if (!names.length) throw new Error('No icon imports found');
const index = ts.createSourceFile('index.js', await readFile(resolve(packageRoot, 'dist/esm/index.js'), 'utf8'), ts.ScriptTarget.Latest, true);
const exports = new Map();
for (const node of index.statements) {
  if (!ts.isExportDeclaration(node) || !node.moduleSpecifier || !ts.isStringLiteral(node.moduleSpecifier)
      || !node.exportClause || !ts.isNamedExports(node.exportClause)) continue;
  for (const item of node.exportClause.elements) {
    if (item.propertyName?.text === 'default') exports.set(item.name.text, node.moduleSpecifier.text);
  }
}
const chunks = [
  '// Generated by scripts/vendor-icons.mjs from @hugeicons/core-free-icons@4.3.0.',
  '// MIT license: see LICENSE.md. Do not edit by hand.',
  'import type { IconSvgElement } from "@hugeicons/react";',
  '',
];
for (const name of names) {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name)) throw new Error(`Invalid icon name: ${name}`);
  const path = exports.get(name);
  if (!path) throw new Error(`Missing upstream export: ${name}`);
  const { default: icon } = await import(pathToFileURL(resolve(packageRoot, 'dist/esm', path)).href);
  if (!Array.isArray(icon) || !icon.length) throw new Error(`Invalid icon: ${name}`);
  chunks.push(`export const ${name}: IconSvgElement = ${JSON.stringify(icon)};`);
}
const output = chunks.join('\n') + '\n';
if (process.argv.includes('--check')) {
  if (await readFile(iconModule, 'utf8') !== output) throw new Error('Vendored icon data differs from upstream');
} else {
  await writeFile(iconModule, output);
}
console.log(`${names.length} icons, ${Buffer.byteLength(output)} bytes${process.argv.includes('--check') ? ', identical to upstream' : ''}`);
